import { WORLD_ROWS } from './constants';

export interface ChunkDef {
  id: string;
  difficulty: 1 | 2 | 3 | 4 | 5;
  entryY: number;
  exitY: number;
  rows: string[];
}

const LEGAL = new Set(['#', '^', 'o', '*', '.']);

export function validateChunk(c: ChunkDef): string[] {
  const errs: string[] = [];
  if (c.rows.length !== WORLD_ROWS) errs.push(`行数 ${c.rows.length} != ${WORLD_ROWS}`);
  const w = c.rows[0]?.length ?? 0;
  if (w < 8) errs.push(`宽度 ${w} < 8`);
  for (const [i, row] of c.rows.entries()) {
    if (row.length !== w) errs.push(`第 ${i} 行宽度不一致`);
    for (const ch of row) if (!LEGAL.has(ch)) errs.push(`第 ${i} 行非法字符 '${ch}'`);
  }
  if (errs.length) return errs;
  const last = w - 1;
  if (c.rows[c.entryY][0] !== '#') errs.push('入口列无地面');
  if (c.rows[c.entryY - 1][0] !== '.') errs.push('入口头顶无空间');
  if (c.rows[c.exitY][last] !== '#') errs.push('出口列无地面');
  if (c.rows[c.exitY - 1][last] !== '.') errs.push('出口头顶无空间');
  return errs;
}

/** 把只写了底部的行数组补齐到 WORLD_ROWS 行（顶部填空行）。 */
function mk(bottomRows: string[]): string[] {
  const w = bottomRows[0].length;
  const padCount = WORLD_ROWS - bottomRows.length;
  return [...Array.from({ length: padCount }, () => '.'.repeat(w)), ...bottomRows];
}

